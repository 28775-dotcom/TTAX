    // Replace remaining invalid UTF-8 bytes with empty or space
    $clean = '';
    $len = strlen($content);
    for ($i = 0; $i < $len; $i++) {
        $ch = $content[$i];
        if (ord($ch) < 128) {
            $clean .= $ch;
        } else {
            // Check 2, 3, 4 byte UTF-8
            for ($bytes = 2; $bytes <= 4; $bytes++) {
                if ($i + $bytes <= $len) {
                    $sub = substr($content, $i, $bytes);
                    if (mb_check_encoding($sub, 'UTF-8')) {
                        $clean .= $sub;
                        $i += $bytes - 1;
                        continue 2;
                    }
                }
            }
            // If invalid byte, skip
        }
    }
